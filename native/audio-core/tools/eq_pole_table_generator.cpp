// Writes the EQ pole correction tables: native/audio-core/src/dsp/eq_pole_table.h and its TypeScript twin
// packages/shared/src/eq-pole-table.ts. Run from the repository root after changing the fit in biquad.h or the
// analog prototypes:
//   c++ -std=c++20 -O2 native/audio-core/tools/eq_pole_table_generator.cpp -o /tmp/eq-pole-table-generator && /tmp/eq-pole-table-generator
// daw-eq-design-poleTable fails when the checked-in tables differ from what this fit produces.
#include "eq_pole_table_fit.h"

#include <cstdio>
#include <string>

namespace {

namespace tools = daw::audio_core::dsp::tools;

std::string numbers(const std::vector<double> &table, size_t gainNodes, const char *indent) {
  const size_t kPerLine = 2 * gainNodes;
  std::string text;
  for (size_t i = 0; i < table.size(); ++i) {
    char value[32];
    std::snprintf(value, sizeof value, "%.6g", table[i] + 0.0);
    text += i % kPerLine == 0 ? indent : " ";
    text += value;
    text += i % kPerLine == kPerLine - 1 ? ",\n" : ",";
  }
  return text;
}

bool write(const char *path, const std::string &text) {
  FILE *file = std::fopen(path, "w");
  if (file == nullptr) return false;
  std::fputs(text.c_str(), file);
  return std::fclose(file) == 0;
}

}  // namespace

int main() {
  const std::vector<double> bell = tools::fitTable(tools::Shape::Bell);
  const std::vector<double> shelf = tools::fitTable(tools::Shape::LowShelf);
  const std::vector<double> lowPass = tools::fitTable(tools::Shape::LowPass);
  constexpr size_t kGains = daw::audio_core::dsp::detail::kPoleTableGainNodes;
  const std::string layout = "one row per corner and Q, the nine gains from -24 to +24 dB inside it (the low-pass has no gain axis), each as (dc, nyquist)";
  const std::string native = "// Generated by native/audio-core/tools/eq_pole_table_generator.cpp. Do not edit.\n"
                             "// Ln change of the pole denominator at DC and at Nyquist for each node of biquad.h's PoleCorrection table:\n// " + layout + ".\n"
                             "#pragma once\n\nnamespace daw::audio_core::dsp::detail {\n\n"
                             "inline constexpr double kBellPoleTable[] = {\n" + numbers(bell, kGains, "  ") + "};\n\n"
                             "inline constexpr double kLowShelfPoleTable[] = {\n" + numbers(shelf, kGains, "  ") + "};\n\n"
                             "inline constexpr double kLowPassPoleTable[] = {\n" + numbers(lowPass, 1, "  ") + "};\n\n}  // namespace daw::audio_core::dsp::detail\n";
  const std::string typescript = "// Generated by native/audio-core/tools/eq_pole_table_generator.cpp. Do not edit.\n"
                                 "// Ln change of the pole denominator at DC and at Nyquist for each node of the PoleCorrection table:\n// " + layout + ".\n\n"
                                 "export const BELL_POLE_TABLE: readonly number[] = [\n" + numbers(bell, kGains, "  ") + "]\n\n"
                                 "export const LOW_SHELF_POLE_TABLE: readonly number[] = [\n" + numbers(shelf, kGains, "  ") + "]\n\n"
                                 "export const LOW_PASS_POLE_TABLE: readonly number[] = [\n" + numbers(lowPass, 1, "  ") + "]\n";
  if (!write("native/audio-core/src/dsp/eq_pole_table.h", native) || !write("packages/shared/src/eq-pole-table.ts", typescript)) {
    std::fprintf(stderr, "could not write the tables; run from the repository root\n");
    return 1;
  }
  return 0;
}
